"""
Pydantic contracts and schemas for resume tailoring, claim verification, and document rendering.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Literal
from uuid import UUID

from pydantic import BaseModel, Field


class FlaggedClaim(BaseModel):
    """An uncorroborated or potentially exaggerated claim requiring user review."""

    claim: str = Field(description="The specific generated text or claim")
    field_path: str = Field(description="JSON path or section where claim occurred")
    reason: str = Field(description="Explanation of why this claim could not be verified")
    severity: Literal["warning", "error"] = Field(
        default="warning",
        description="Severity ('warning' for unconfirmed nuances, 'error' for invented facts)",
    )


class TailoredExperienceEntry(BaseModel):
    """Experience entry in tailored resume."""

    company: str
    title: str
    start_date: str | None = None
    end_date: str | None = None
    location: str | None = None
    bullet_points: list[str] = Field(
        default_factory=list,
        description="2 to 4 crisp, tailored bullet points actively rewritten to align with target qualifications",
    )


class TailoredProjectEntry(BaseModel):
    """Project entry in tailored resume."""

    name: str = ""
    description: str | None = None
    bullet_points: list[str] = Field(
        default_factory=list,
        description="Tailored bullet points highlighting relevant achievements, tech stack, and impact",
    )
    technologies: list[str] = Field(default_factory=list)
    url: str | None = None
    date: str | None = None


class TailoredEducationEntry(BaseModel):
    """Education entry in tailored resume."""

    institution: str = ""
    degree: str = ""
    field_of_study: str | None = None
    start_date: str | None = None
    end_date: str | None = None
    gpa: str | None = None
    location: str | None = None
    coursework: list[str] = Field(
        default_factory=list,
        description="Relevant coursework selected to match the target job requirements",
    )


class TailoredResumeContent(BaseModel):
    """Structured tailored resume content produced by AI model."""

    headline: str = Field(description="Job-targeted professional title / headline")
    summary: str = Field(description="Job-tailored professional summary")
    skills: list[str] = Field(
        default_factory=list,
        description="Prioritized skills strictly derived from verified profile",
    )
    experience: list[TailoredExperienceEntry] = Field(default_factory=list)
    education: list[TailoredEducationEntry] = Field(default_factory=list)
    certifications: list[dict[str, Any]] = Field(default_factory=list)
    projects: list[TailoredProjectEntry] = Field(default_factory=list)


class TailorResumeRequest(BaseModel):
    """Request payload to generate a tailored resume for a target job."""

    job_id: UUID = Field(description="Target job listing UUID")
    profile_version_id: UUID | None = Field(
        default=None,
        description="Optional profile version ID; if omitted, uses active profile",
    )
    template_version: str = Field(
        default="modern-clean-v1",
        description="Resume visual template identifier",
    )
    target_role_notes: str | None = Field(
        default=None,
        description="Optional candidate notes or target role focus",
    )


class TailorPreviewRequest(BaseModel):
    """Payload to generate AI-tailored resume content preview with Gemini."""

    job: dict[str, Any] = Field(description="Target job listing details")
    candidate_profile: dict[str, Any] = Field(description="Candidate profile facts")
    target_role_notes: str | None = Field(default=None, description="Optional focus notes")


class UpdateTailoredContentRequest(BaseModel):
    """Payload for user edits to structured tailored resume content."""

    structured_content: TailoredResumeContent


class TailoredDocumentResponse(BaseModel):
    """API representation of a tailored document record."""

    id: UUID
    user_id: UUID
    job_id: UUID
    profile_version_id: UUID
    status: Literal["pending", "generating", "review_required", "approved", "failed"]
    structured_content: TailoredResumeContent | None = None
    storage_path: str | None = None
    download_url: str | None = None
    flagged_claims: list[FlaggedClaim] = Field(default_factory=list)
    validation_passed: bool | None = None
    validation_version: str | None = None
    scoring_version: str | None = None
    template_version: str | None = None
    model_used: str | None = None
    generation_latency_ms: int | None = None
    error_summary: str | None = None
    created_at: datetime
    updated_at: datetime


class CoverLetterContent(BaseModel):
    """Structured tailored cover letter generated by Gemini with deep company research."""

    recipient: str = Field(
        default="Hiring Team",
        description="Target team or recipient title (e.g. 'Engineering Hiring Team')",
    )
    company_name: str = Field(description="Target company name")
    salutation: str = Field(
        description="Personalized salutation (e.g. 'Dear Stripe Engineering Team,')",
    )
    opening_hook: str = Field(
        description="Natural, engaging opening hook demonstrating real understanding of the company mission, products, and role fit",
    )
    body_paragraphs: list[str] = Field(
        default_factory=list,
        description="2 to 3 natural, conversational yet professional paragraphs connecting candidate's genuine achievements and tech stack with company's mission",
    )
    call_to_action: str = Field(
        description="Confident, conversational closing expressing excitement to discuss further",
    )
    signoff: str = Field(
        default="Sincerely,",
        description="Closing signoff phrase",
    )
    candidate_name: str = Field(
        default="",
        description="Candidate's full name",
    )
    full_text: str = Field(
        default="",
        description="Complete assembled cover letter formatted for display and editing",
    )
    company_research_summary: str | None = Field(
        default=None,
        description="Summary of key company insights and focus areas discovered during search/research",
    )


class CoverLetterPreviewRequest(BaseModel):
    """Request payload to generate an AI-tailored cover letter with Gemini."""

    job: dict[str, Any] = Field(description="Target job listing details")
    candidate_profile: dict[str, Any] = Field(description="Candidate profile facts")
    target_role_notes: str | None = Field(
        default=None,
        description="Optional focus notes or candidate custom priorities",
    )
    tone: Literal["natural_conversational", "enthusiastic", "formal"] = Field(
        default="natural_conversational",
        description="Voice and tone preference",
    )

